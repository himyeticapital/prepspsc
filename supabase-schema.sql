-- PrepSPSC Database Schema
-- Run this SQL in your Supabase SQL Editor

-- 1. Profiles (Links to Supabase Auth)
create table public.profiles (
  id uuid references auth.users primary key,
  username text unique,
  full_name text,
  avatar_url text,
  bio text,
  role text default 'user' check (role in ('user', 'teacher', 'admin')),
  total_minutes_all_time integer default 0,
  current_streak integer default 0,
  max_streak integer default 0,
  is_pro_member boolean default false,
  pro_expires_at timestamptz,
  created_at timestamptz default now()
);

-- 2. Study Logs (for heatmap)
create table public.daily_study_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) not null,
  study_date date default current_date,
  minutes_studied integer default 0,
  unique(user_id, study_date)
);

-- 3. Exam Categories (Sikkim SPSC specific)
create table public.exam_categories (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  icon text,
  sort_order integer default 0
);

-- 4. Tests
create table public.tests (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  category_id bigint references public.exam_categories(id),
  is_premium boolean default false,
  duration_minutes integer default 60,
  total_marks integer,
  passing_marks integer,
  created_by uuid references public.profiles(id),
  created_at timestamptz default now()
);

-- 5. Questions (MCQ + Conventional)
create table public.questions (
  id bigint generated by default as identity primary key,
  test_id bigint references public.tests(id) on delete cascade,
  content text not null,
  type text not null check (type in ('mcq', 'conventional')),
  options jsonb,
  correct_answer text,
  marks integer default 1,
  negative_marks numeric default 0,
  explanation text,
  sort_order integer default 0
);

-- 6. Test Attempts
create table public.test_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id),
  test_id bigint references public.tests(id),
  started_at timestamptz default now(),
  completed_at timestamptz,
  score integer,
  total_marks integer,
  time_taken_seconds integer,
  status text default 'in_progress' check (status in ('in_progress', 'completed', 'abandoned'))
);

-- 7. User Answers
create table public.user_answers (
  id bigint generated by default as identity primary key,
  attempt_id bigint references public.test_attempts(id) on delete cascade,
  question_id bigint references public.questions(id),
  user_answer text,
  is_correct boolean,
  marks_obtained numeric default 0
);

-- 8. Bookmarks
create table public.bookmarks (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id),
  question_id bigint references public.questions(id),
  notes text,
  created_at timestamptz default now(),
  unique(user_id, question_id)
);

-- 9. Chat Rooms
create table public.rooms (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  category text,
  is_active boolean default true,
  created_at timestamptz default now()
);

-- 10. Messages
create table public.messages (
  id bigint generated by default as identity primary key,
  room_id bigint references public.rooms(id) on delete cascade,
  user_id uuid references public.profiles(id),
  content text,
  type text default 'text',
  is_deleted boolean default false,
  deleted_by uuid references public.profiles(id),
  created_at timestamptz default now()
);

-- 11. Payments
create table public.payments (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id),
  cashfree_order_id text,
  cashfree_payment_id text,
  amount integer,
  currency text default 'INR',
  status text check (status in ('created', 'paid', 'failed')),
  plan_type text check (plan_type in ('monthly', 'yearly')),
  created_at timestamptz default now()
);

