-- Create function to auto-create profile on signup
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, full_name, avatar_url, username)
  values (
    new.id,
    new.raw_user_meta_data->>'full_name',
    new.raw_user_meta_data->>'avatar_url',
    split_part(new.email, '@', 1)
  );
  return new;
end;
$$ language plpgsql security definer;

-- Trigger to auto-create profile
create or replace trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Function to increment study time
create or replace function increment_study_time(user_id uuid, minutes integer)
returns void as $$
begin
  update profiles
  set total_minutes_all_time = total_minutes_all_time + minutes
  where id = user_id;
end;
$$ language plpgsql security definer;

-- Function to log study time (upsert daily log)
create or replace function log_study_time(p_user_id uuid, p_minutes integer)
returns void as $$
begin
  insert into daily_study_logs (user_id, study_date, minutes_studied)
  values (p_user_id, current_date, p_minutes)
  on conflict (user_id, study_date)
  do update set minutes_studied = daily_study_logs.minutes_studied + p_minutes;

  -- Also update total
  update profiles
  set total_minutes_all_time = total_minutes_all_time + p_minutes
  where id = p_user_id;
end;
$$ language plpgsql security definer;

