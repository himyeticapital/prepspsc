-- RLS Policies

-- Profiles: Users can read all profiles but only update their own
create policy "Public profiles are viewable by everyone" on public.profiles
  for select using (true);

create policy "Users can update own profile" on public.profiles
  for update using (auth.uid() = id);

create policy "Users can insert own profile" on public.profiles
  for insert with check (auth.uid() = id);

-- Daily Study Logs: Users can only access their own logs
create policy "Users can view own study logs" on public.daily_study_logs
  for select using (auth.uid() = user_id);

create policy "Users can insert own study logs" on public.daily_study_logs
  for insert with check (auth.uid() = user_id);

create policy "Users can update own study logs" on public.daily_study_logs
  for update using (auth.uid() = user_id);

-- Exam Categories: Public read
create policy "Exam categories are viewable by everyone" on public.exam_categories
  for select using (true);

create policy "Admins can manage categories" on public.exam_categories
  for all using (
    exists (select 1 from profiles where id = auth.uid() and role = 'admin')
  );

-- Tests: Public read for all tests
create policy "Tests are viewable by everyone" on public.tests
  for select using (true);

create policy "Admins and teachers can manage tests" on public.tests
  for all using (
    exists (select 1 from profiles where id = auth.uid() and role in ('admin', 'teacher'))
