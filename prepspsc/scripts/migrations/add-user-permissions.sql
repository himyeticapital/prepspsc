-- Migration: Add granular user permissions system
-- Run this in Supabase SQL Editor

-- Create permissions table to store user permissions
CREATE TABLE IF NOT EXISTS public.user_permissions (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade not null,
  permission text not null,
  granted_by uuid references public.profiles(id),
  granted_at timestamptz default now(),
  unique(user_id, permission)
);

-- Enable RLS
ALTER TABLE public.user_permissions ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if they exist (for re-running migration)
DROP POLICY IF EXISTS "Permissions are viewable by everyone" ON public.user_permissions;
DROP POLICY IF EXISTS "Admins can manage permissions" ON public.user_permissions;

-- Everyone can read permissions (needed for permission checks)
CREATE POLICY "Permissions are viewable by everyone" ON public.user_permissions
  FOR SELECT USING (true);

-- Only admins can manage permissions
CREATE POLICY "Admins can manage permissions" ON public.user_permissions
  FOR ALL USING (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  );

-- Add permissions column to profiles for quick access (optional, for caching)
-- This stores an array of permission strings for faster lookups
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'profiles' AND column_name = 'permissions'
  ) THEN
    ALTER TABLE public.profiles ADD COLUMN permissions text[] DEFAULT '{}';
  END IF;
END $$;

-- Function to check if user has a specific permission
CREATE OR REPLACE FUNCTION has_permission(user_id uuid, permission_name text)
RETURNS boolean AS $$
BEGIN
  -- Admins have all permissions
  IF EXISTS (SELECT 1 FROM profiles WHERE id = user_id AND role = 'admin') THEN
    RETURN true;
  END IF;

  -- Check specific permission
  RETURN EXISTS (
    SELECT 1 FROM user_permissions
    WHERE user_permissions.user_id = $1 AND permission = permission_name
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to grant permission to user
CREATE OR REPLACE FUNCTION grant_permission(target_user_id uuid, permission_name text, granter_id uuid)
RETURNS void AS $$
BEGIN
  -- Only admins can grant permissions
  IF NOT EXISTS (SELECT 1 FROM profiles WHERE id = granter_id AND role = 'admin') THEN
    RAISE EXCEPTION 'Only admins can grant permissions';
  END IF;

  INSERT INTO user_permissions (user_id, permission, granted_by)
  VALUES (target_user_id, permission_name, granter_id)
  ON CONFLICT (user_id, permission) DO NOTHING;

  -- Update cached permissions array
  UPDATE profiles
  SET permissions = (
    SELECT array_agg(permission) FROM user_permissions WHERE user_permissions.user_id = target_user_id
  )
  WHERE id = target_user_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to revoke permission from user
CREATE OR REPLACE FUNCTION revoke_permission(target_user_id uuid, permission_name text, revoker_id uuid)
RETURNS void AS $$
BEGIN
  -- Only admins can revoke permissions
  IF NOT EXISTS (SELECT 1 FROM profiles WHERE id = revoker_id AND role = 'admin') THEN
    RAISE EXCEPTION 'Only admins can revoke permissions';
  END IF;

  DELETE FROM user_permissions
  WHERE user_id = target_user_id AND permission = permission_name;

  -- Update cached permissions array
  UPDATE profiles
  SET permissions = COALESCE(
    (SELECT array_agg(permission) FROM user_permissions WHERE user_permissions.user_id = target_user_id),
    '{}'
  )
  WHERE id = target_user_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

