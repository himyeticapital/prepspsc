-- Function to create a new table (with validation)
CREATE OR REPLACE FUNCTION create_study_table(
  p_room_id bigint,
  p_name text,
  p_user_id uuid
)
RETURNS jsonb AS $$
DECLARE
  v_table_count integer;
  v_max_tables integer;
  v_is_banned boolean;
  v_new_table_id bigint;
  v_room_active boolean;
BEGIN
  -- Check if room exists and is active
  SELECT is_active, max_tables INTO v_room_active, v_max_tables
  FROM rooms WHERE id = p_room_id;

  IF v_room_active IS NULL THEN
    RETURN jsonb_build_object('success', false, 'error', 'Room not found');
  END IF;

  IF NOT v_room_active THEN
    RETURN jsonb_build_object('success', false, 'error', 'Room is not active');
  END IF;

  -- Check if user is banned from room
  SELECT is_user_banned(p_user_id, p_room_id) INTO v_is_banned;

  IF v_is_banned THEN
    RETURN jsonb_build_object('success', false, 'error', 'You are banned from this room');
  END IF;

  -- Get current table count
  SELECT COUNT(*) INTO v_table_count
  FROM study_tables WHERE room_id = p_room_id;

  IF v_table_count >= v_max_tables THEN
    RETURN jsonb_build_object('success', false, 'error', 'Maximum tables reached in this room');
  END IF;

  -- Leave any existing table first
  PERFORM leave_table(p_user_id);

  -- Create new table
  INSERT INTO study_tables (room_id, name, created_by)
  VALUES (p_room_id, p_name, p_user_id)
  RETURNING id INTO v_new_table_id;

  -- Auto-join the creator
  INSERT INTO table_members (table_id, user_id)
  VALUES (v_new_table_id, p_user_id);

  RETURN jsonb_build_object('success', true, 'table_id', v_new_table_id);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to join an existing table (with validation)
CREATE OR REPLACE FUNCTION join_table(p_user_id uuid, p_table_id bigint)
RETURNS jsonb AS $$
DECLARE
  v_current_count integer;
  v_max_capacity integer;
  v_room_id bigint;
  v_is_banned boolean;
BEGIN
  -- Get table info
  SELECT room_id, max_capacity INTO v_room_id, v_max_capacity
  FROM study_tables WHERE id = p_table_id;

  IF v_room_id IS NULL THEN
    RETURN jsonb_build_object('success', false, 'error', 'Table not found');
  END IF;

  -- Check if user is banned from room
  SELECT is_user_banned(p_user_id, v_room_id) INTO v_is_banned;

  IF v_is_banned THEN
    RETURN jsonb_build_object('success', false, 'error', 'You are banned from this room');
  END IF;

  -- Get current member count
  SELECT COUNT(*) INTO v_current_count
  FROM table_members WHERE table_id = p_table_id;

  IF v_current_count >= v_max_capacity THEN
    RETURN jsonb_build_object('success', false, 'error', 'Table is full');
  END IF;

  -- Leave any existing table first
  PERFORM leave_table(p_user_id);

  -- Join new table
  INSERT INTO table_members (table_id, user_id)
  VALUES (p_table_id, p_user_id);

  RETURN jsonb_build_object('success', true);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to leave a table (with auto-delete if empty)
CREATE OR REPLACE FUNCTION leave_table(p_user_id uuid)
RETURNS void AS $$
DECLARE
  v_table_id bigint;
  v_remaining_count integer;
BEGIN
  -- Get user's current table
  SELECT table_id INTO v_table_id
  FROM table_members WHERE user_id = p_user_id;

  IF v_table_id IS NULL THEN
    RETURN;
  END IF;

  -- Remove user from table
  DELETE FROM table_members WHERE user_id = p_user_id;

  -- Check if table is now empty
  SELECT COUNT(*) INTO v_remaining_count
  FROM table_members WHERE table_id = v_table_id;

  -- Delete table if empty (ephemeral behavior)
  IF v_remaining_count = 0 THEN
    DELETE FROM study_tables WHERE id = v_table_id;
  END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to kick a user from their table (admin only)
CREATE OR REPLACE FUNCTION kick_from_table(p_admin_id uuid, p_user_id uuid)
RETURNS jsonb AS $$
DECLARE
  v_is_admin boolean;
BEGIN
  -- Verify caller is admin
  SELECT (role = 'admin') INTO v_is_admin
  FROM profiles WHERE id = p_admin_id;

  IF NOT v_is_admin THEN
    RETURN jsonb_build_object('success', false, 'error', 'Not authorized');
  END IF;

  -- Leave the table (will auto-delete if empty)
  PERFORM leave_table(p_user_id);

  RETURN jsonb_build_object('success', true);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to ban a user from a room (admin only)
CREATE OR REPLACE FUNCTION ban_user_from_room(
  p_admin_id uuid,
  p_user_id uuid,
  p_room_id bigint,
  p_reason text DEFAULT NULL,
  p_duration_hours integer DEFAULT NULL  -- NULL = permanent
)
RETURNS jsonb AS $$
DECLARE
  v_is_admin boolean;
  v_expires_at timestamptz;
BEGIN
  -- Verify caller is admin
  SELECT (role = 'admin') INTO v_is_admin
  FROM profiles WHERE id = p_admin_id;

  IF NOT v_is_admin THEN
    RETURN jsonb_build_object('success', false, 'error', 'Not authorized');
  END IF;

  -- Calculate expiry if duration provided
  IF p_duration_hours IS NOT NULL THEN
    v_expires_at := NOW() + (p_duration_hours || ' hours')::interval;
  END IF;

  -- First kick them from any table in this room
  DELETE FROM table_members
  WHERE user_id = p_user_id
  AND table_id IN (SELECT id FROM study_tables WHERE room_id = p_room_id);

  -- Insert or update ban
  INSERT INTO room_bans (room_id, user_id, banned_by, reason, expires_at)
  VALUES (p_room_id, p_user_id, p_admin_id, p_reason, v_expires_at)
  ON CONFLICT (room_id, user_id)
  DO UPDATE SET
    banned_by = p_admin_id,
    reason = p_reason,
    banned_at = NOW(),
    expires_at = v_expires_at;

  RETURN jsonb_build_object('success', true);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to unban a user from a room (admin only)
CREATE OR REPLACE FUNCTION unban_user_from_room(
  p_admin_id uuid,
  p_user_id uuid,
  p_room_id bigint
)
RETURNS jsonb AS $$
DECLARE
  v_is_admin boolean;
BEGIN
  -- Verify caller is admin
  SELECT (role = 'admin') INTO v_is_admin
  FROM profiles WHERE id = p_admin_id;

  IF NOT v_is_admin THEN
    RETURN jsonb_build_object('success', false, 'error', 'Not authorized');
  END IF;

  -- Remove ban
  DELETE FROM room_bans
  WHERE room_id = p_room_id AND user_id = p_user_id;

  RETURN jsonb_build_object('success', true);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

