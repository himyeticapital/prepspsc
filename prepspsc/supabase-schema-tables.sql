-- 7. HELPER FUNCTIONS
-- ============================================

-- Function to get table member count
CREATE OR REPLACE FUNCTION get_table_member_count(p_table_id bigint)
RETURNS integer AS $$
BEGIN
  RETURN (
    SELECT COUNT(*)::integer
    FROM table_members
    WHERE table_id = p_table_id
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to check if user is banned from a room
CREATE OR REPLACE FUNCTION is_user_banned(p_user_id uuid, p_room_id bigint)
RETURNS boolean AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM room_bans
    WHERE room_id = p_room_id
    AND user_id = p_user_id
    AND (expires_at IS NULL OR expires_at > NOW())
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to get user's current table in a room
CREATE OR REPLACE FUNCTION get_user_table(p_user_id uuid, p_room_id bigint)
RETURNS bigint AS $$
BEGIN
  RETURN (
    SELECT st.id
    FROM study_tables st
    INNER JOIN table_members tm ON tm.table_id = st.id
    WHERE tm.user_id = p_user_id AND st.room_id = p_room_id
    LIMIT 1
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- ============================================
-- 8. MAIN FUNCTIONS FOR TABLE OPERATIONS
