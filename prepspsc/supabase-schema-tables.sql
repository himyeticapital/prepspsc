-- ============================================
-- 1. MODIFY ROOMS TABLE (Study Halls - Admin Only)
-- ============================================

-- Add admin control columns to rooms
ALTER TABLE public.rooms
  ADD COLUMN IF NOT EXISTS max_tables integer DEFAULT 20,
  ADD COLUMN IF NOT EXISTS sort_order integer DEFAULT 0,
  ADD COLUMN IF NOT EXISTS created_by uuid REFERENCES public.profiles(id);

-- ============================================
-- 2. CREATE STUDY_TABLES TABLE (Ephemeral 4-person groups)
-- ============================================

CREATE TABLE IF NOT EXISTS public.study_tables (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id bigint REFERENCES public.rooms(id) ON DELETE CASCADE NOT NULL,
  name text NOT NULL,
  created_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  max_capacity integer DEFAULT 4,
  created_at timestamptz DEFAULT now(),
  CONSTRAINT valid_capacity CHECK (max_capacity > 0 AND max_capacity <= 8),
  CONSTRAINT valid_name_length CHECK (char_length(name) <= 50)
);

-- Enable RLS
ALTER TABLE public.study_tables ENABLE ROW LEVEL SECURITY;

-- RLS Policies for study_tables
CREATE POLICY "Tables are viewable by everyone" ON public.study_tables
  FOR SELECT USING (true);

CREATE POLICY "Authenticated users can create tables" ON public.study_tables
  FOR INSERT WITH CHECK (
    auth.uid() IS NOT NULL
  );

CREATE POLICY "Table creators can update their tables" ON public.study_tables
  FOR UPDATE USING (created_by = auth.uid());

CREATE POLICY "Table creators and admins can delete" ON public.study_tables
  FOR DELETE USING (
    created_by = auth.uid() OR
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  );

-- Index for quick lookups
CREATE INDEX IF NOT EXISTS idx_study_tables_room ON study_tables(room_id);
CREATE INDEX IF NOT EXISTS idx_study_tables_created_by ON study_tables(created_by);

-- ============================================
-- 3. CREATE TABLE_MEMBERS TABLE
-- ============================================

CREATE TABLE IF NOT EXISTS public.table_members (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_id bigint REFERENCES public.study_tables(id) ON DELETE CASCADE NOT NULL,
  user_id uuid REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  joined_at timestamptz DEFAULT now(),
  last_seen_at timestamptz DEFAULT now(),
  UNIQUE(table_id, user_id),
  UNIQUE(user_id) -- User can only be at one table at a time
);

-- Enable RLS
ALTER TABLE public.table_members ENABLE ROW LEVEL SECURITY;

-- RLS Policies for table_members
CREATE POLICY "Table members are viewable by everyone" ON public.table_members
  FOR SELECT USING (true);

CREATE POLICY "Users can join tables" ON public.table_members
  FOR INSERT WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update their own membership" ON public.table_members
  FOR UPDATE USING (auth.uid() = user_id);

CREATE POLICY "Users can leave tables" ON public.table_members
  FOR DELETE USING (auth.uid() = user_id);

CREATE POLICY "Admins can kick users from tables" ON public.table_members
  FOR DELETE USING (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  );

-- Indexes
CREATE INDEX IF NOT EXISTS idx_table_members_table ON table_members(table_id);
CREATE INDEX IF NOT EXISTS idx_table_members_user ON table_members(user_id);

-- ============================================
-- 4. MODIFY MESSAGES TABLE (Dual Chat Support)
-- ============================================

ALTER TABLE public.messages
  ADD COLUMN IF NOT EXISTS table_id bigint REFERENCES public.study_tables(id) ON DELETE CASCADE,
  ADD COLUMN IF NOT EXISTS message_scope text DEFAULT 'room';

-- Add constraint for message_scope
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'messages_scope_check'
  ) THEN
    ALTER TABLE public.messages ADD CONSTRAINT messages_scope_check
      CHECK (message_scope IN ('room', 'table'));
  END IF;
END $$;

-- Indexes for message queries
CREATE INDEX IF NOT EXISTS idx_messages_table ON public.messages(table_id) WHERE table_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_messages_scope ON public.messages(room_id, message_scope);

-- Update messages RLS to handle table privacy
DROP POLICY IF EXISTS "Messages are viewable by room participants" ON public.messages;
DROP POLICY IF EXISTS "Messages viewable by everyone" ON public.messages;

CREATE POLICY "Messages viewable based on scope" ON public.messages
  FOR SELECT USING (
    -- Room messages are public
    message_scope = 'room' OR
    -- Table messages only visible to table members
    (message_scope = 'table' AND EXISTS (
      SELECT 1 FROM public.table_members
      WHERE table_members.table_id = messages.table_id
      AND table_members.user_id = auth.uid()
    )) OR
    -- Admins can see all messages
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  );

-- ============================================
-- 5. CREATE ROOM_BANS TABLE (Moderation)
-- ============================================

CREATE TABLE IF NOT EXISTS public.room_bans (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id bigint REFERENCES public.rooms(id) ON DELETE CASCADE NOT NULL,
  user_id uuid REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  banned_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  reason text,
  banned_at timestamptz DEFAULT now(),
  expires_at timestamptz, -- NULL = permanent ban
  UNIQUE(room_id, user_id)
);

-- Enable RLS
ALTER TABLE public.room_bans ENABLE ROW LEVEL SECURITY;

-- RLS Policies for room_bans
CREATE POLICY "Admins can view all bans" ON public.room_bans
  FOR SELECT USING (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  );

CREATE POLICY "Users can check own ban status" ON public.room_bans
  FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "Admins can manage bans" ON public.room_bans
  FOR ALL USING (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  );

-- Indexes
CREATE INDEX IF NOT EXISTS idx_room_bans_lookup ON room_bans(room_id, user_id);
CREATE INDEX IF NOT EXISTS idx_room_bans_expiry ON room_bans(expires_at) WHERE expires_at IS NOT NULL;

-- ============================================
-- 6. UPDATE ROOMS RLS (Admin-only management)
-- ============================================

-- Drop old policies that allow user creation
DROP POLICY IF EXISTS "Users can create public rooms" ON public.rooms;
DROP POLICY IF EXISTS "Owners can update own rooms" ON public.rooms;
DROP POLICY IF EXISTS "Anyone can view active rooms" ON public.rooms;

-- Rooms are viewable by everyone
CREATE POLICY "Rooms are viewable by everyone" ON public.rooms
  FOR SELECT USING (true);

-- Only admins can manage rooms (Study Halls)
CREATE POLICY "Admins can manage study halls" ON public.rooms
  FOR INSERT WITH CHECK (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  );

CREATE POLICY "Admins can update study halls" ON public.rooms
  FOR UPDATE USING (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  );

CREATE POLICY "Admins can delete study halls" ON public.rooms
  FOR DELETE USING (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  );

