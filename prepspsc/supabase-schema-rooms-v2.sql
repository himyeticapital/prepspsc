-- Add new columns to rooms table
ALTER TABLE public.rooms ADD COLUMN IF NOT EXISTS privacy_level text DEFAULT 'public' CHECK (privacy_level IN ('public', 'private', 'premium'));
ALTER TABLE public.rooms ADD COLUMN IF NOT EXISTS owner_id uuid REFERENCES public.profiles(id);
ALTER TABLE public.rooms ADD COLUMN IF NOT EXISTS max_members integer DEFAULT 100;
ALTER TABLE public.rooms ADD COLUMN IF NOT EXISTS tags text[] DEFAULT '{}';
ALTER TABLE public.rooms ADD COLUMN IF NOT EXISTS icon text;
ALTER TABLE public.rooms ADD COLUMN IF NOT EXISTS color text DEFAULT 'teal';

-- ============================================
-- 2. USER ROOM SUBSCRIPTIONS TABLE
-- ============================================

CREATE TABLE IF NOT EXISTS public.user_room_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  room_id bigint REFERENCES public.rooms(id) ON DELETE CASCADE NOT NULL,
  joined_at timestamptz DEFAULT now(),
  is_favorite boolean DEFAULT false,
  notification_level text DEFAULT 'normal' CHECK (notification_level IN ('muted', 'normal', 'important')),
  last_read_at timestamptz DEFAULT now(),
  UNIQUE(user_id, room_id)
);

-- Enable RLS
ALTER TABLE public.user_room_subscriptions ENABLE ROW LEVEL SECURITY;

-- RLS Policies for subscriptions
CREATE POLICY "Users can view own subscriptions" ON public.user_room_subscriptions
  FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "Users can insert own subscriptions" ON public.user_room_subscriptions
  FOR INSERT WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update own subscriptions" ON public.user_room_subscriptions
  FOR UPDATE USING (auth.uid() = user_id);

CREATE POLICY "Users can delete own subscriptions" ON public.user_room_subscriptions
  FOR DELETE USING (auth.uid() = user_id);

-- ============================================
-- 3. ROOM NOTIFICATIONS TABLE
-- ============================================

CREATE TABLE IF NOT EXISTS public.room_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  room_id bigint REFERENCES public.rooms(id) ON DELETE CASCADE NOT NULL,
  type text NOT NULL CHECK (type IN ('new_message', 'mention', 'room_update', 'member_joined')),
  title text NOT NULL,
  message text,
  metadata jsonb DEFAULT '{}',
  is_read boolean DEFAULT false,
  created_at timestamptz DEFAULT now()
);

-- Enable RLS
ALTER TABLE public.room_notifications ENABLE ROW LEVEL SECURITY;

-- RLS Policies for notifications
CREATE POLICY "Users can view own notifications" ON public.room_notifications
  FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "Users can update own notifications" ON public.room_notifications
  FOR UPDATE USING (auth.uid() = user_id);

CREATE POLICY "Users can delete own notifications" ON public.room_notifications
  FOR DELETE USING (auth.uid() = user_id);

-- System can insert notifications (using service role)
CREATE POLICY "Service role can insert notifications" ON public.room_notifications
  FOR INSERT WITH CHECK (true);

-- ============================================
-- 4. ROOM PRESENCE TABLE (for tracking online users)
-- ============================================

CREATE TABLE IF NOT EXISTS public.room_presence (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  room_id bigint REFERENCES public.rooms(id) ON DELETE CASCADE NOT NULL,
  last_seen_at timestamptz DEFAULT now(),
  status text DEFAULT 'online' CHECK (status IN ('online', 'away', 'studying')),
  UNIQUE(user_id, room_id)
);

-- Enable RLS
ALTER TABLE public.room_presence ENABLE ROW LEVEL SECURITY;

-- RLS Policies for presence (public read, users manage their own)
CREATE POLICY "Anyone can view presence" ON public.room_presence
  FOR SELECT USING (true);

CREATE POLICY "Users can manage own presence" ON public.room_presence
  FOR ALL USING (auth.uid() = user_id);

-- ============================================
-- 5. UPDATE ROOMS RLS POLICIES
-- ============================================

-- Drop existing policies first
DROP POLICY IF EXISTS "Rooms are viewable by everyone" ON public.rooms;
DROP POLICY IF EXISTS "Admins can manage rooms" ON public.rooms;

-- New policy: Public rooms visible to all, private rooms only to members/owners
CREATE POLICY "Rooms visibility based on privacy" ON public.rooms
  FOR SELECT USING (
    privacy_level = 'public' OR
    owner_id = auth.uid() OR
    (privacy_level = 'premium' AND EXISTS (
      SELECT 1 FROM profiles WHERE id = auth.uid() AND is_pro_member = true
    )) OR
    EXISTS (
      SELECT 1 FROM user_room_subscriptions
      WHERE user_room_subscriptions.room_id = rooms.id
      AND user_room_subscriptions.user_id = auth.uid()
    )
  );

-- Admins can manage all rooms
CREATE POLICY "Admins can manage rooms" ON public.rooms
  FOR ALL USING (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  );

-- Users can create public rooms
CREATE POLICY "Users can create public rooms" ON public.rooms
  FOR INSERT WITH CHECK (
    auth.uid() IS NOT NULL AND
    privacy_level = 'public'
  );

-- Owners can update their own rooms
CREATE POLICY "Owners can update own rooms" ON public.rooms
  FOR UPDATE USING (owner_id = auth.uid());

