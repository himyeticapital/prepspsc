-- 6. FUNCTIONS
-- ============================================

-- Function to get online count for a room
CREATE OR REPLACE FUNCTION get_room_online_count(p_room_id bigint)
RETURNS integer AS $$
BEGIN
  RETURN (
    SELECT COUNT(*)::integer
    FROM room_presence
    WHERE room_id = p_room_id
    AND last_seen_at > NOW() - INTERVAL '5 minutes'
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to update presence (heartbeat)
CREATE OR REPLACE FUNCTION update_room_presence(p_user_id uuid, p_room_id bigint, p_status text DEFAULT 'online')
RETURNS void AS $$
BEGIN
  INSERT INTO room_presence (user_id, room_id, last_seen_at, status)
  VALUES (p_user_id, p_room_id, NOW(), p_status)
  ON CONFLICT (user_id, room_id)
  DO UPDATE SET last_seen_at = NOW(), status = p_status;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to leave room (remove presence)
CREATE OR REPLACE FUNCTION leave_room_presence(p_user_id uuid, p_room_id bigint)
RETURNS void AS $$
BEGIN
  DELETE FROM room_presence WHERE user_id = p_user_id AND room_id = p_room_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to get unread notification count
CREATE OR REPLACE FUNCTION get_unread_notification_count(p_user_id uuid)
RETURNS integer AS $$
BEGIN
  RETURN (
    SELECT COUNT(*)::integer
    FROM room_notifications
    WHERE user_id = p_user_id AND is_read = false
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to mark notifications as read for a room
CREATE OR REPLACE FUNCTION mark_room_notifications_read(p_user_id uuid, p_room_id bigint)
RETURNS void AS $$
BEGIN
  UPDATE room_notifications
  SET is_read = true
  WHERE user_id = p_user_id AND room_id = p_room_id AND is_read = false;

  -- Also update last_read_at in subscription
  UPDATE user_room_subscriptions
  SET last_read_at = NOW()
  WHERE user_id = p_user_id AND room_id = p_room_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to search rooms
CREATE OR REPLACE FUNCTION search_rooms(search_query text, p_user_id uuid DEFAULT NULL)
RETURNS SETOF rooms AS $$
BEGIN
  RETURN QUERY
  SELECT r.*
  FROM rooms r
  WHERE r.is_active = true
  AND (
    r.privacy_level = 'public' OR
    r.owner_id = p_user_id OR
    (r.privacy_level = 'premium' AND EXISTS (
      SELECT 1 FROM profiles WHERE id = p_user_id AND is_pro_member = true
    )) OR
    EXISTS (
      SELECT 1 FROM user_room_subscriptions
      WHERE room_id = r.id AND user_id = p_user_id
    )
  )
  AND (
    r.name ILIKE '%' || search_query || '%' OR
    r.description ILIKE '%' || search_query || '%' OR
    r.category ILIKE '%' || search_query || '%' OR
    search_query = ANY(r.tags)
  )
  ORDER BY r.created_at DESC;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

